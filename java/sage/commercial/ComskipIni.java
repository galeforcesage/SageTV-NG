package sage.commercial;

import java.io.BufferedWriter;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * Parses and flattens layered Comskip INI files.
 *
 * <p>Comskip resolves a setting from its first active occurrence, so concatenating
 * overlay files does not provide normal last-layer-wins behavior. This helper
 * preserves first-occurrence behavior inside each source file, applies later
 * layers semantically, and writes one active definition per key.</p>
 */
final class ComskipIni
{
  private ComskipIni()
  {
  }

  /**
   * Reads the active settings in one INI layer.
   *
   * @param path the INI file to read
   * @return settings in source order, with the first occurrence of each key retained
   * @throws IOException if the file cannot be read
   */
  static LinkedHashMap<String, String> readLayer(Path path) throws IOException
  {
    LinkedHashMap<String, String> values = new LinkedHashMap<>();
    for (String line : Files.readAllLines(path, StandardCharsets.UTF_8))
    {
      String trimmed = line.trim();
      if (trimmed.isEmpty() || trimmed.startsWith(";") || trimmed.startsWith("#") ||
          trimmed.startsWith("["))
        continue;

      int equals = trimmed.indexOf('=');
      if (equals <= 0)
        continue;

      String key = normalizeKey(trimmed.substring(0, equals));
      if (key == null)
        continue;

      values.putIfAbsent(key, trimmed.substring(equals + 1).trim());
    }
    return values;
  }

  /**
   * Merges INI layers from lowest to highest precedence.
   *
   * @param layers ordered INI paths; null and missing optional paths are ignored
   * @param runtimeOverrides highest-precedence runtime settings, or null
   * @return the flattened effective settings
   * @throws IOException if an existing layer cannot be read
   */
  static LinkedHashMap<String, String> mergeLayers(List<Path> layers,
      Map<String, String> runtimeOverrides) throws IOException
  {
    LinkedHashMap<String, String> effective = new LinkedHashMap<>();
    if (layers != null)
    {
      for (Path layer : layers)
      {
        if (layer != null && Files.isRegularFile(layer))
          effective.putAll(readLayer(layer));
      }
    }

    if (runtimeOverrides != null)
    {
      for (Map.Entry<String, String> entry : runtimeOverrides.entrySet())
      {
        String key = normalizeKey(entry.getKey());
        if (key != null)
          effective.put(key, entry.getValue() == null ? "" : entry.getValue());
      }
    }
    return effective;
  }

  /**
   * Writes one active definition per setting to a generated INI file.
   *
   * @param values effective setting map
   * @param profileName descriptive profile name used in the temporary filename
   * @param directory temporary-file directory, or null for the system default
   * @return the generated INI path
   * @throws IOException if the file cannot be written
   */
  static Path writeEffectiveIni(Map<String, String> values, String profileName,
      Path directory) throws IOException
  {
    String safeName = profileName == null ? "effective" :
        profileName.toLowerCase(Locale.ROOT).replaceAll("[^a-z0-9_-]+", "_");
    if (safeName.length() < 3)
      safeName = "effective";
    String prefix = "comskip_" + safeName + "_";
    Path output = directory == null
        ? Files.createTempFile(prefix, ".ini")
        : Files.createTempFile(directory, prefix, ".ini");

    try (BufferedWriter writer = Files.newBufferedWriter(output, StandardCharsets.UTF_8))
    {
      writer.write("; Generated by SageTV-NG; do not edit");
      writer.newLine();
      writer.write("; One active definition per setting");
      writer.newLine();
      for (Map.Entry<String, String> entry : values.entrySet())
      {
        writer.write(entry.getKey());
        writer.write('=');
        writer.write(entry.getValue());
        writer.newLine();
      }
    }
    output.toFile().deleteOnExit();
    return output;
  }

  /**
   * Normalizes and validates a Comskip setting key.
   *
   * @param rawKey untrusted key text
   * @return normalized key, or null when invalid
   */
  private static String normalizeKey(String rawKey)
  {
    if (rawKey == null)
      return null;
    String key = rawKey.trim().toLowerCase(Locale.ROOT);
    return key.matches("[a-z0-9_]+") ? key : null;
  }
}
